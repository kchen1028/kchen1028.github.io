// ============================================================
// i18n engine
// ============================================================
(function() {
  const STORAGE_KEY = 'preferred-lang';
  let currentLang = localStorage.getItem(STORAGE_KEY) || 'zh';

  function t(key) {
    return (translations[currentLang] && translations[currentLang][key]) || key;
  }

  function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);

    // Update document language
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';

    // Update meta tags
    document.title = t('meta.title');
    const desc = document.querySelector('meta[name="description"]');
    if (desc) desc.setAttribute('content', t('meta.description'));

    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = t(key);
      // If value contains HTML tags, use innerHTML
      if (val.includes('<')) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    });

    // Update elements with data-i18n-attr (for attributes like aria-label, alt, etc.)
    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
      const attrMap = JSON.parse(el.getAttribute('data-i18n-attr'));
      for (const attr in attrMap) {
        el.setAttribute(attr, t(attrMap[attr]));
      }
    });

    // Update stat values (structured elements)
    updateStats();

    // Update tags (arrays)
    updateTags();

    // Update skill bars (re-trigger animation)
    // (Skill bars are visual only, names are handled by data-i18n)

    // Update language button state
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    // Update resume download links
    const resumeUrl = lang === 'zh' ? 'chenkai-resume.pdf' : 'Kai_Chen_Resume_EN.pdf';
    const resumeFileName = lang === 'zh' ? '陈凯-简历.pdf' : 'Kai_Chen_Resume.pdf';
    document.querySelectorAll('#heroResumeBtn, #contactResumeBtn').forEach(btn => {
      btn.setAttribute('href', resumeUrl);
      btn.setAttribute('download', resumeFileName);
    });

    // Update download button in contact section label if needed
    // (handled by data-i18n on the label text already)

    // Emit event for any custom JS that needs to react
    document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
  }

  function updateStats() {
    // Hero stats have value + unit structure handled by data-i18n on child spans
    // Already covered by data-i18n traversal above
  }

  function updateTags() {
    // Tag groups that need array translation
    // We handle them by setting data-i18n-tags on the container
    document.querySelectorAll('[data-i18n-tags]').forEach(container => {
      const keyBase = container.getAttribute('data-i18n-tags');
      const tags = t(keyBase);
      if (Array.isArray(tags)) {
        container.innerHTML = tags.map(tag => `<span>${tag}</span>`).join('');
      }
    });
  }

  // Initialize on DOM ready
  function init() {
    // Create language switcher button and inject into nav
    const navCta = document.querySelector('.nav-cta');
    if (navCta) {
      const langSwitcher = document.createElement('div');
      langSwitcher.className = 'lang-switcher';
      langSwitcher.innerHTML = `
        <button class="lang-btn" data-lang="zh" aria-label="Switch to Chinese">中</button>
        <span class="lang-divider">|</span>
        <button class="lang-btn" data-lang="en" aria-label="Switch to English">EN</button>
      `;
      // Insert before the CTA button
      navCta.parentNode.insertBefore(langSwitcher, navCta);

      langSwitcher.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
          setLanguage(btn.dataset.lang);
        });
      });
    }

    // Apply initial language
    setLanguage(currentLang);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

  // Expose globally
  window.i18n = { setLanguage, t, get currentLang() { return currentLang; } };
})();
