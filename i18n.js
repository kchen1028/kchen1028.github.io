// ============================================================
// i18n engine
// ============================================================
(function() {
  const STORAGE_KEY = 'preferred-lang';

  // localStorage 在部分内嵌浏览器（如微信 WebView）中可能抛异常，
  // 必须包起来，否则整个 i18n 会失效。
  function readLang() {
    try { return localStorage.getItem(STORAGE_KEY); } catch (e) { return null; }
  }
  function writeLang(lang) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* 忽略 */ }
  }

  let currentLang = readLang() || 'zh';
  if (!translations[currentLang]) currentLang = 'zh';

  function t(key) {
    const dict = translations[currentLang];
    // 用 hasOwnProperty 判断「键是否存在」，而不是「值是否为真值」——
    // 否则被翻译成空字符串的键（如英文不需要的单位后缀）会回退成 key 本身。
    if (dict && Object.prototype.hasOwnProperty.call(dict, key)) {
      return dict[key];
    }
    return key;
  }

  function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    writeLang(lang);

    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';

    document.title = t('meta.title');
    const desc = document.querySelector('meta[name="description"]');
    if (desc) desc.setAttribute('content', t('meta.description'));

    // 文本节点
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const val = t(el.getAttribute('data-i18n'));
      if (typeof val !== 'string') return;
      // 译文含标签时用 innerHTML（如 hero.desc 里的 <strong>）
      if (val.includes('<')) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    });

    // 属性（aria-label / content / alt 等）
    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
      let attrMap;
      try {
        attrMap = JSON.parse(el.getAttribute('data-i18n-attr'));
      } catch (e) {
        return;
      }
      for (const attr in attrMap) {
        el.setAttribute(attr, t(attrMap[attr]));
      }
    });

    // 标签组（数组）
    document.querySelectorAll('[data-i18n-tags]').forEach(container => {
      const tags = t(container.getAttribute('data-i18n-tags'));
      if (Array.isArray(tags)) {
        container.innerHTML = tags.map(tag => `<span>${tag}</span>`).join('');
      }
    });

    // 语言按钮状态
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
      btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang));
    });

    // 简历下载链接随语言切换
    const resumeUrl = lang === 'zh' ? 'chenkai-resume.pdf' : 'Kai_Chen_Resume_EN.pdf';
    const resumeFileName = lang === 'zh' ? '陈凯-简历.pdf' : 'Kai_Chen_Resume.pdf';
    document.querySelectorAll('#heroResumeBtn, #contactResumeBtn').forEach(btn => {
      btn.setAttribute('href', resumeUrl);
      btn.setAttribute('download', resumeFileName);
    });

    document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
  }

  function init() {
    const navCta = document.querySelector('.nav-cta');
    if (navCta) {
      const langSwitcher = document.createElement('div');
      langSwitcher.className = 'lang-switcher';
      langSwitcher.setAttribute('role', 'group');
      langSwitcher.setAttribute('aria-label', '语言 / Language');
      langSwitcher.innerHTML = `
        <button class="lang-btn" type="button" data-lang="zh" aria-label="切换到中文">中</button>
        <span class="lang-divider" aria-hidden="true">|</span>
        <button class="lang-btn" type="button" data-lang="en" aria-label="Switch to English">EN</button>
      `;
      navCta.parentNode.insertBefore(langSwitcher, navCta);

      langSwitcher.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
      });
    }

    setLanguage(currentLang);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

  window.i18n = { setLanguage, t, get currentLang() { return currentLang; } };
})();
